/** Sinh các polyline (mm) để in chuỗi `str`, gốc trái-dưới (x,y), chiều cao 6·s. */
export function textStrokes(str: string, x: number, y: number, s: number): { x: number; y: number }[][] {
  const out: { x: number; y: number }[][] = []
  let ox = x
  for (const ch of str.toUpperCase()) {
    const g = F[ch] ?? F[' ']
    for (const st of g) out.push(st.map(([gx, gy]) => ({ x: ox + gx * s, y: y + gy * s })))
    ox += 5 * s
  }
  return out
}
/** Bề rộng (mm) khi in chuỗi với hệ số s. */
export function textWidth(str: string, s: number) { return Math.max(0, str.length * 5 - 1) * s }
