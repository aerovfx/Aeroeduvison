import { promises as fs } from "node:fs";
import path from "node:path";

const repoRoot = "/Users/pixibox/Aeroeduvison";
const apiDir = path.join(repoRoot, "app", "api");
const docsDir = path.join(repoRoot, "docs", "rust-migration");
const rustInventoryPath = path.join(repoRoot, "rust-services", "aero-backend", "src", "inventory.rs");

const batch1Routes = new Set(["/api/vector-similarity", "/api/ocr-grading"]);
const batch2Routes = new Set(["/api/ocr/auto-grade", "/api/ocr-process"]);
const batch3Routes = new Set(["/api/ocr/upload"]);
const batch4Routes = new Set(["/api/llm-grading", "/api/assignments/grade-ocr"]);

type InventoryItem = {
  route: string;
  sourceFile: string;
  status: "migrated" | "scaffolded";
  batch: "batch-1" | "batch-2" | "batch-3" | "batch-4" | "backlog";
  targetService: "rust" | "node";
  notes: string;
};

async function walk(dir: string): Promise<string[]> {
  const entries = await fs.readdir(dir, { withFileTypes: true });
  const files: string[] = [];

  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...(await walk(fullPath)));
      continue;
    }
    if (entry.isFile() && entry.name === "route.ts") {
      files.push(fullPath);
    }
  }

  return files;
}

function toRoutePattern(filePath: string): string {
  const rel = path.relative(apiDir, filePath).replace(/\\/g, "/");
  const noSuffix = rel.replace(/\/route\.ts$/, "");
  return noSuffix ? `/api/${noSuffix}` : "/api";
}

function escapeRustString(input: string): string {
  return input.replace(/\\/g, "\\\\").replace(/\"/g, '\\\"');
}

async function main() {
  const files = await walk(apiDir);
  const inventory: InventoryItem[] = files
    .map((filePath) => {
      const route = toRoutePattern(filePath);
      const isBatch1 = batch1Routes.has(route);
      const isBatch2 = batch2Routes.has(route);
      const isBatch3 = batch3Routes.has(route);
      const isBatch4 = batch4Routes.has(route);
      const isMigrated = isBatch1 || isBatch2 || isBatch3 || isBatch4;
      return {
        route,
        sourceFile: path.relative(repoRoot, filePath).replace(/\\/g, "/"),
        status: isMigrated ? "migrated" : "scaffolded",
        batch: isBatch1 ? "batch-1" : isBatch2 ? "batch-2" : isBatch3 ? "batch-3" : isBatch4 ? "batch-4" : "backlog",
        targetService: isMigrated ? "rust" : "node",
        notes: isMigrated ? "Implemented in rust-services/aero-backend" : "Scaffold placeholder (501) in Rust backend"
      } satisfies InventoryItem;
    })
    .sort((a, b) => a.route.localeCompare(b.route));

  const jsonPath = path.join(docsDir, "api-inventory.json");
  await fs.writeFile(jsonPath, JSON.stringify({ generatedAt: new Date().toISOString(), total: inventory.length, items: inventory }, null, 2));

  const csvHeader = "route,source_file,status,batch,target_service,notes";
  const csvRows = inventory.map((item) => {
    const safe = (v: string) => `\"${v.replace(/\"/g, '""')}\"`;
    return [safe(item.route), safe(item.sourceFile), safe(item.status), safe(item.batch), safe(item.targetService), safe(item.notes)].join(",");
  });
  await fs.writeFile(path.join(docsDir, "migration-matrix.csv"), [csvHeader, ...csvRows].join("\n"));

  const mdLines = [
    "# API Migration Matrix",
    "",
    `Generated: ${new Date().toISOString()}`,
    ``,
    `Total routes: **${inventory.length}**`,
    "",
    "| Route | Source | Status | Batch | Target | Notes |",
    "|---|---|---|---|---|---|"
  ];

  for (const item of inventory) {
    mdLines.push(`| \`${item.route}\` | \`${item.sourceFile}\` | ${item.status} | ${item.batch} | ${item.targetService} | ${item.notes} |`);
  }

  await fs.writeFile(path.join(docsDir, "migration-matrix.md"), mdLines.join("\n"));

  const rustKnown = inventory.map((item) => `    \"${escapeRustString(item.route)}\",`);
  const rustMigrated = inventory
    .filter((item) => item.status === "migrated")
    .map((item) => `    \"${escapeRustString(item.route)}\",`);

  const rustModule = `// Auto-generated by scripts/rust-migration/generate-inventory.ts\n\npub const KNOWN_API_ROUTES: &[&str] = &[\n${rustKnown.join("\n")}\n];\n\npub const MIGRATED_API_ROUTES: &[&str] = &[\n${rustMigrated.join("\n")}\n];\n`;

  await fs.writeFile(rustInventoryPath, rustModule);

  console.log(`Generated inventory for ${inventory.length} API routes.`);
  console.log(`- ${path.relative(repoRoot, jsonPath)}`);
  console.log(`- docs/rust-migration/migration-matrix.csv`);
  console.log(`- docs/rust-migration/migration-matrix.md`);
  console.log(`- ${path.relative(repoRoot, rustInventoryPath)}`);
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
